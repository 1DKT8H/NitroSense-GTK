#!/bin/sh
set -eu
ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
STAGE="$ROOT/packaging/debian"
OUT="$ROOT/packaging/nitrosense_0.5.0_all.deb"
rm -rf "$STAGE/usr"
mkdir -p "$STAGE/usr/lib/python3/dist-packages" "$STAGE/usr/bin" "$STAGE/usr/share"
cp -a "$ROOT/src/nitrosense" "$STAGE/usr/lib/python3/dist-packages/"
find "$STAGE/usr/lib/python3/dist-packages/nitrosense" -type d -name __pycache__ -prune -exec rm -rf {} +
cp -a "$ROOT/share/." "$STAGE/usr/share/"
cp "$ROOT/share/icons/hicolor/scalable/apps/nitrosense.svg" \
  "$STAGE/usr/share/icons/hicolor/scalable/apps/io.github.nitrosense.NitroSense.svg"
mkdir -p "$STAGE/usr/lib/systemd/user"
cp "$ROOT/systemd/nitrosense-hotkeys.service" "$STAGE/usr/lib/systemd/user/"
mkdir -p "$STAGE/usr/lib/systemd/system" "$STAGE/usr/lib/nitrosense" "$STAGE/usr/src/nitrosense-rgb-0.3.0"
cp "$ROOT/systemd/nitrosense-hardware.service" "$ROOT/systemd/nitrosense-platform.service" "$STAGE/usr/lib/systemd/system/"
cp "$ROOT/packaging/setup-platform" "$STAGE/usr/lib/nitrosense/"
chmod 755 "$STAGE/usr/lib/nitrosense/setup-platform"
cp "$ROOT/kernel/nitrosense_rgb.c" "$ROOT/kernel/Makefile" "$ROOT/kernel/dkms.conf" "$ROOT/kernel/NOTICE.md" "$STAGE/usr/src/nitrosense-rgb-0.3.0/"
cp /usr/share/common-licenses/GPL-2 "$STAGE/usr/src/nitrosense-rgb-0.3.0/LICENSE"
printf '#!/bin/sh\nexec /usr/bin/python3 -I -m nitrosense.__main__ "$@"\n' > "$STAGE/usr/bin/nitrosense"
printf '#!/bin/sh\nexec /usr/bin/python3 -I -m nitrosense.helper "$@"\n' > "$STAGE/usr/bin/nitrosense-helper"
printf '#!/bin/sh\nexec /usr/bin/python3 -I -m nitrosense.overlay "$@"\n' > "$STAGE/usr/bin/nitrosense-overlay"
chmod 755 "$STAGE/usr/bin/nitrosense" "$STAGE/usr/bin/nitrosense-helper" "$STAGE/usr/bin/nitrosense-overlay"
printf '#!/bin/sh\nexec /usr/bin/python3 -I -m nitrosense.routine "$@"\n' > "$STAGE/usr/bin/nitrosense-routine"
chmod 755 "$STAGE/usr/bin/nitrosense-routine"
cp "$STAGE/usr/bin/nitrosense-overlay" "$STAGE/usr/bin/nitrosense-game"
cp "$ROOT/packaging/nitrosense-hotkey" "$STAGE/usr/bin/nitrosense-hotkey"
chmod 755 "$STAGE/usr/bin/nitrosense-hotkey"
chmod 755 "$STAGE/DEBIAN/postinst" "$STAGE/DEBIAN/prerm" "$STAGE/DEBIAN/postrm"
dpkg-deb --root-owner-group --build "$STAGE" "$OUT"
echo "Built $OUT"
